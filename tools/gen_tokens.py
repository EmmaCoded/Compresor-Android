#!/usr/bin/env python3
"""Generates Tokens.kt (Jetpack Compose) from design/tokens.json.

    py -3 tools/gen_tokens.py            # writes app/src/main/java/app/compresor/ui/theme/Tokens.kt
    py -3 tools/gen_tokens.py PATH.kt    # or to another path

Components use only these names, never a hand-written color or size.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
TARGET = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "app" / "src" / "main" / "java" / "app" / "compresor" / "ui" / "theme" / "Tokens.kt"


def camel(name: str) -> str:
    parts = name.split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def color(hexa: str) -> str:
    return "Color(0xFF%s)" % hexa.lstrip("#").upper()


def main() -> None:
    t = json.loads(SOURCE.read_text(encoding="utf-8"))
    dark = {k: v for k, v in t["color"].items() if not k.startswith("light-")}
    light = {k[len("light-"):]: v for k, v in t["color"].items() if k.startswith("light-")}
    if set(dark) != set(light):
        sys.exit("The two themes do not have the same roles: %s" % sorted(set(dark) ^ set(light)))

    s = []
    s.append("// GENERATED by tools/gen_tokens.py from design/tokens.json. Do not edit by hand.")
    s.append("package app.compresor.ui.theme")
    s.append("")
    s.append("import androidx.compose.ui.graphics.Color")
    s.append("import androidx.compose.ui.text.font.FontWeight")
    s.append("import androidx.compose.ui.unit.dp")
    s.append("import androidx.compose.ui.unit.sp")
    s.append("")
    s.append("data class Palette(")
    for k in dark:
        s.append("    val %s: Color," % camel(k))
    s.append(")")
    s.append("")
    for name, theme in (("DarkPalette", dark), ("LightPalette", light)):
        s.append("val %s = Palette(" % name)
        for k in dark:
            s.append("    %s = %s," % (camel(k), color(theme[k])))
        s.append(")")
        s.append("")
    s.append("object Spacing {")
    for i, v in enumerate(t["space"]):
        s.append("    val e%d = %d.dp" % (i, v))
    s.append("}")
    s.append("")
    s.append("object Radius {")
    for k, v in t["radius"].items():
        s.append("    val %s = %d.dp" % (camel(k), v))
    s.append("}")
    s.append("")
    s.append("object Dimens {")
    for k, v in t["size"].items():
        s.append("    val %s = %d.dp" % (camel(k), v))
    s.append("}")
    s.append("")
    s.append("data class Typo(val size: Int, val line: Int, val weight: Int)")
    s.append("")
    s.append("object Type {")
    for k, v in t["type"].items():
        s.append("    val %s = Typo(%d, %d, %d)" % (camel(k), v["size"], v["line"], v["weight"]))
    s.append("}")
    s.append("")
    s.append("object Movement {")
    for k, v in t["motion"].items():
        s.append("    const val %s = %d  // ms" % (camel(k), v))
    s.append("}")
    s.append("")
    # sp/FontWeight are imported so the theme layer can turn Typo into a TextStyle
    s.append("fun Typo.sizeSp() = size.sp")
    s.append("fun Typo.lineSp() = line.sp")
    s.append("fun Typo.fontWeight() = FontWeight(weight)")
    s.append("")
    TARGET.write_text("\n".join(s), encoding="utf-8", newline="\n")
    print("written:", TARGET)


if __name__ == "__main__":
    main()
